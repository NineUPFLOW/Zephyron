namespace Zephyron.Core.Rules;

/// <summary>
/// Что держать мимо туннеля, когда полный перехват включён ради правила по программе.
/// </summary>
/// <remarks>
/// <para>
/// Правило «программа → VPN» заводит в туннель весь трафик машины
/// (<see cref="RuleSet.RoutesProgramIntoTunnel"/>): на Windows sing-box узнаёт
/// процесс только внутри туннеля, и выбрать программу иначе нельзя. Всё без
/// правила идёт из туннеля в <c>direct</c> — наружу оно выходит, но уже через
/// движок туннеля, а не своим путём.
/// </para>
/// <para>
/// Для игр это не всё равно. Обсуждение №11 (30.09): Valorant при маршрутах
/// в VPN «идёт через VPN», пинг прыгает до 200. Было ли у того человека правило
/// по программе, не установлено, — но при таком правиле игровой UDP Valorant
/// шёл бы через движок туннеля, хотя сама Riot стоит на десинке.
/// </para>
/// <para>
/// Поэтому сети, у которых есть свой адресный список и маршрут мимо VPN, при
/// таком перехвате выводятся из туннеля: они идут ровно как без правила
/// по программе. Пока это одна Riot (AS6507, <c>config/lists/riot-network.txt</c>):
/// у прочих игр списка адресов у нас нет, а по именам из туннеля не вывести.
/// </para>
/// </remarks>
public static class ProgramCapture
{
    /// <summary>
    /// Сети Riot — игровые серверы Valorant и League; часть «Игровой UDP» в «Маршрутах».
    /// </summary>
    public const string RiotNetwork = "config/lists/riot-network.txt";

    /// <summary>
    /// Адресные списки, которые при полном перехвате ради программы идут мимо туннеля.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Riot — если её игровая часть не «через VPN»: отправленную в VPN выводить
    /// из туннеля нельзя. Маршрут — первого правила по списку сетей, как решает
    /// и движок. Правила нет — Riot идёт мимо VPN, и сети выводятся.
    /// </para>
    /// <para>
    /// До 30.09 решал маршрут имён Riot. С разделением на «Вход и клиент»
    /// и «Игровой UDP» решает вторая часть: вход через VPN при игре напрямую —
    /// ровно то, что советуют игрокам (обсуждение №11), и вход от этого не
    /// страдает — имена при полном перехвате получают подменный адрес и идут
    /// в туннель мимо этого исключения.
    /// </para>
    /// </remarks>
    /// <summary>
    /// Забирает ли туннель всё ради правила «программа → VPN».
    /// </summary>
    /// <remarks>
    /// <para>
    /// Теперь и при десинке. Прежде полный перехват при нём не включался
    /// (владелец, 01.10): весь трафик машины шёл через sing-box, и winws2 видел
    /// каждое соединение дважды — по дороге в TUN и на выходе из движка; 01.10
    /// так умер голос Discord. Но именно из-за этого условия правило программы
    /// при десинке не работало вовсе: процесс sing-box узнаёт только внутри TUN,
    /// а выборочный перехват заводит туда лишь адреса из правил, и серверы игры
    /// по голым адресам шли мимо (обсуждение №10, «добавление программы ничем
    /// не помогло»). Владелец 04.10 тогда выбрал снять такие правила, а не
    /// молча обещать несуществующее.
    /// </para>
    /// <para>
    /// Двойной проход с тех пор закрыт: пакеты по дороге в туннель и из него
    /// несут адрес нашего TUN, и <see cref="Zephyron.Zapret.TunnelCapture"/>
    /// выводит их из перехвата winws2 (<c>TunnelEndpoints.TunAddresses</c>,
    /// замер 01.10). Сети, которым десинк не нужен, дополнительно уходят
    /// из туннеля в <c>route_exclude_address</c> и в фильтр перехвата
    /// (<see cref="KeepOut"/>), поэтому игра на десинке не гонится через движок
    /// туннеля, как в обсуждении №11.
    /// </para>
    /// <para>
    /// Цена остаётся: при полном перехвате через движок туннеля проходит весь
    /// трафик машины, а не только программа. Куда что идёт, решают маршруты,
    /// и всё без правила уходит в <c>direct</c>.
    /// </para>
    /// </remarks>
    public static bool ForcesFullCapture(RuleSet ruleSet, bool desyncRuns) =>
        ruleSet.RoutesProgramIntoTunnel;

    public static IReadOnlyList<string> KeepOut(RuleSet ruleSet)
    {
        if (!ruleSet.RoutesProgramIntoTunnel)
            return [];

        var riot = ruleSet.Rules.FirstOrDefault(r =>
            r.Enabled
            && r.Match == MatchKind.IpSet
            && IsRiotNetwork(r.Value));

        return riot?.Mode == RoutingMode.Proxy ? [] : [RiotNetwork];
    }

    private static bool IsRiotNetwork(string value) =>
        value.Replace('\\', '/').EndsWith("/" + Path.GetFileName(RiotNetwork), StringComparison.OrdinalIgnoreCase);
}
